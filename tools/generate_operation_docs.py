"""Generate the operation reference so every catalog entry has a docs row."""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from mission_control.operation_catalog import OPERATIONS  # noqa: E402

TARGET = ROOT / "docs/operation-catalog.md"
HEADER = """# Operation catalog

Generated by `python tools/generate_operation_docs.py`; do not edit by hand.
Each row mirrors a closed descriptor in `mission_control/operation_catalog.py`.

| Operation | Method | Suffix | Effect | Required | Optional | Query |
| --- | --- | --- | --- | --- | --- | --- |
"""


def cell(values):
    return ", ".join(f"`{value}`" for value in values) or "-"


def render():
    rows = []
    for name in sorted(OPERATIONS):
        operation = OPERATIONS[name]
        rows.append(
            "| `%s` | `%s` | `%s` | `%s` | %s | %s | %s |"
            % (
                name,
                operation["method"],
                operation["suffix"] or "/",
                operation["effect"],
                cell(operation["required"]),
                cell(operation["optional"]),
                cell(operation.get("query", [])),
            )
        )
    return HEADER + "\n".join(rows) + "\n"


def main(argv):
    value = render()
    if "--check" in argv:
        current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
        if current != value:
            print("OPERATION_DOCS_DRIFT regenerate docs/operation-catalog.md", file=sys.stderr)
            return 1
        print("OPERATION_DOCS_CURRENT")
        return 0
    TARGET.write_text(value, encoding="utf-8")
    print(f"WROTE {TARGET.relative_to(ROOT).as_posix()}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
