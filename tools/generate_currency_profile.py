"""Generate browser currency exponents from the frozen local ISO profile; no network."""

import argparse
import sys
from pathlib import Path


def main() -> None:
    sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
    from mission_control.currency_units import CURRENCY_DIGITS, PUBLISHED_AT, SOURCE_SHA256

    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    target = Path(__file__).resolve().parents[1] / "mission_control/static/currency-profile.mjs"
    content = (
        "// Generated by python tools/generate_currency_profile.py; do not edit.\n"
        f"// Frozen ISO source: {SOURCE_SHA256}; published {PUBLISHED_AT}.\n"
        "export const CURRENCY_DIGITS = Object.freeze({\n"
        + "\n".join(f"  {code}: {digits}," for code, digits in sorted(CURRENCY_DIGITS.items()))
        + "\n});\n"
    )
    if args.check:
        if target.read_text(encoding="utf-8") != content:
            raise SystemExit("Currency profile differs from the frozen Python source; regenerate.")
        print(f"PASS: {len(CURRENCY_DIGITS)} frozen currency profiles match")
    else:
        target.write_text(content, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
